package auth

import (
	"fmt"
	"strings"

	"go-dsc-pull/internal/schema"
)

// minimumSecretLen is the recommended minimum length (in characters) for a
// secret used as an HMAC/JWT signing key. 32 random characters from a 62-char
// alphabet is ~190 bits; 32 random bytes (base64) is 256 bits. We use 32 as a
// conservative floor for both secrets.
const minimumSecretLen = 32

// knownWeakSecrets lists values that are clearly placeholders or defaults and
// must be replaced before production use.
var knownWeakSecrets = map[string]bool{
	"example-shared-secret": true,
	"your-strong-secret":    true,
	"anysecret":             true,
	"anykey":                true,
	"changeme":              true,
	"password":              true,
	"secret":                true,
	"anyregistrationkey":    true,
}

// SecurityWarnings inspects the resolved configuration and returns a list of
// startup warnings for secrets that are missing or too weak to be used safely.
// It is intended to be emitted once at boot, next to the existing empty-value
// checks.
func SecurityWarnings(appCfg *schema.AppConfig) []string {
	if appCfg == nil {
		return nil
	}

	var warnings []string

	// shared_secret drives JWT signing for the web/API. ResolveJWTSecret already
	// applies the web_ui.shared_secret -> dsc_pullserver.shared_secret priority.
	if w := assessSecret("shared_secret", ResolveJWTSecret(appCfg)); w != "" {
		warnings = append(warnings, w)
	}

	// registrationKey is used as the HMAC key for DSC node registration.
	if w := assessSecret("dsc_pullserver.registrationKey", appCfg.DSCPullServer.RegistrationKey); w != "" {
		warnings = append(warnings, w)
	}

	return warnings
}

// FatalSecurityErrors inspects the resolved configuration and returns a list
// of fatal startup errors that must cause the server to refuse to start
// (fail-closed). Unlike SecurityWarnings, these are hard failures: emitting a
// warning and continuing would let an operator believe a protection is active
// when it is not (fail-open).
func FatalSecurityErrors(appCfg *schema.AppConfig) []string {
	if appCfg == nil {
		return nil
	}

	var errs []string

	// Fail-closed: if client-certificate validation is enabled but the DSC
	// endpoint is served over plain HTTP, no client certificate is negotiated
	// on the pull endpoints, so they are NOT protected by mutual TLS. The
	// operator would believe mTLS is on when it is not. Refuse to start.
	if appCfg.DSCPullServer.EnableClientCertValidation && !appCfg.DSCPullServer.EnableHTTPS {
		errs = append(errs, fmt.Sprintf(
			"ERROR [SECURITY] enable_client_cert_validation is true but enable_https is false: the DSC pull endpoints would be served over plain HTTP with no client certificate (mTLS) protection. Refusing to start (fail-closed). Set enable_https: true and provide cert_file/key_file, or set enable_client_cert_validation: false."))
	}

	return errs
}

// assessSecret returns a startup warning for a weak or placeholder secret, or
// an empty string when the secret is acceptable. An empty value is reported
// separately by the caller's existing empty-value checks, so it returns "".
func assessSecret(name, value string) string {
	v := strings.TrimSpace(value)
	if v == "" {
		return ""
	}

	if len(v) < minimumSecretLen {
		return fmt.Sprintf("WARN [SECURITY] %s is only %d characters long (recommended minimum: %d). Generate a strong random value (see scripts/Generate-SecureKeys.ps1).", name, len(v), minimumSecretLen)
	}

	if knownWeakSecrets[strings.ToLower(v)] {
		return fmt.Sprintf("WARN [SECURITY] %s is a well-known placeholder value. Replace it with a strong random secret (see scripts/Generate-SecureKeys.ps1).", name)
	}

	// Low character diversity usually means the value was typed by hand rather
	// than generated by a CSPRNG. Distinctly weak values are flagged.
	if distinctChars(v) <= 10 {
		return fmt.Sprintf("WARN [SECURITY] %s has low character diversity (%d unique characters). Use a strong random secret (see scripts/Generate-SecureKeys.ps1).", name, distinctChars(v))
	}

	return ""
}

// distinctChars returns the number of distinct runes in s.
func distinctChars(s string) int {
	seen := make(map[rune]struct{}, len(s))
	for _, r := range s {
		seen[r] = struct{}{}
	}
	return len(seen)
}
